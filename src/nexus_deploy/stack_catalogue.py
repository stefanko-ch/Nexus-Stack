"""Generate the stack catalogue in ``docs/stacks/overview.md`` from ``services.yaml``.

The catalogue used to be written by hand, three times: a table in the top-level
README, one in ``docs/stacks/README.md`` and one in ``docs/stacks/overview.md``.
The last one is what nexus-stack.ch shows as "Stacks Overview", and it was the
one nobody updated: after a release that brought the repository to 163 stacks it
still said "60+" and listed 68.

So the table is no longer written. ``services.yaml`` already holds every value
it shows, and this module renders them into the block between two marker
comments. Everything outside the markers stays hand-written.

Regenerate after changing ``services.yaml``, adding a stack page or renaming a
category::

    uv run python -m nexus_deploy.stack_catalogue

``tests/unit/test_stack_catalogue.py`` fails when the committed block differs
from what this module renders.

Three inputs, each the existing source of truth for what it supplies:

* ``services.yaml`` — which stacks exist, their category, description, image
  and tier.
* ``docs/stacks/<slug>.md`` — the display name, from the ``title`` in its
  frontmatter. It is the name the website's sidebar already shows.
* ``control-plane/src/lib/categories.ts`` — category names and their order, so
  the catalogue groups stacks exactly as the Control Plane does.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

BEGIN_MARKER = "<!-- BEGIN stack-catalogue (generated by `python -m nexus_deploy.stack_catalogue`; do not edit) -->"
END_MARKER = "<!-- END stack-catalogue -->"

# A stack whose page is not named after its services.yaml key. Renaming the page
# would change its URL on nexus-stack.ch, so the exception is recorded instead.
PAGE_SLUGS = {"woodpecker": "woodpecker-ci"}

_CATEGORY = re.compile(r"^\s*'([a-z0-9-]+)':\s*\{\s*name:\s*'([^']+)'", re.MULTILINE)
_ORDER_BLOCK = re.compile(r"CATEGORY_ORDER\s*=\s*\[(.*?)\]", re.DOTALL)


class CatalogueError(ValueError):
    """An input the catalogue needs is missing or inconsistent."""


def page_slug(slug: str) -> str:
    """Return the file stem of a stack's page under ``docs/stacks/``."""
    return PAGE_SLUGS.get(slug, slug)


@dataclass(frozen=True)
class Stack:
    slug: str
    name: str
    category: str
    description: str
    image: str
    tier: str


def read_categories(categories_ts: str) -> list[tuple[str, str]]:
    """Return ``(key, display name)`` pairs in the Control Plane's order."""
    names = dict(_CATEGORY.findall(categories_ts))
    order_block = _ORDER_BLOCK.search(categories_ts)
    if not names or order_block is None:
        raise CatalogueError("categories.ts: could not read CATEGORIES or CATEGORY_ORDER")
    order = re.findall(r"'([a-z0-9-]+)'", order_block.group(1))
    unnamed = [key for key in order if key not in names]
    unordered = [key for key in names if key not in order]
    if unnamed or unordered:
        raise CatalogueError(
            f"categories.ts: CATEGORIES and CATEGORY_ORDER disagree "
            f"(in order but unnamed: {unnamed}; named but not in order: {unordered})"
        )
    return [(key, names[key]) for key in order]


def read_title(page: str) -> str | None:
    """Return the ``title`` from a page's frontmatter, or None when it has none."""
    if not page.startswith("---\n"):
        return None
    end = page.find("\n---", 4)
    if end == -1:
        return None
    try:
        frontmatter = yaml.safe_load(page[4:end])
    except yaml.YAMLError:
        return None
    if not isinstance(frontmatter, dict):
        return None
    title = frontmatter.get("title")
    return title.strip() or None if isinstance(title, str) else None


def _tier(entry: dict[str, Any]) -> str:
    if entry.get("core"):
        return "core"
    return str(entry.get("tier") or "best-effort")


def collect_stacks(
    services: dict[str, dict[str, Any]], titles: dict[str, str | None]
) -> list[Stack]:
    """Turn ``services.yaml`` entries into catalogue rows.

    An entry with a ``stack`` key is a second service inside another stack's
    directory (``seaweedfs-filer`` lives in ``stacks/seaweedfs``). It has no
    page of its own and is not a stack, so it gets no row.
    """
    stacks: list[Stack] = []
    missing_title: list[str] = []
    incomplete: list[str] = []
    for slug, entry in services.items():
        if "stack" in entry:
            continue
        absent = [key for key in ("category", "description", "image") if not entry.get(key)]
        if absent:
            incomplete.append(f"{slug} (no {', '.join(absent)})")
            continue
        title = titles.get(slug)
        if not title:
            missing_title.append(slug)
            continue
        stacks.append(
            Stack(
                slug=slug,
                name=title,
                category=str(entry["category"]),
                description=" ".join(str(entry["description"]).split()),
                image=str(entry["image"]),
                tier=_tier(entry),
            )
        )
    if incomplete:
        raise CatalogueError(f"services.yaml entries the catalogue cannot render: {incomplete}")
    if missing_title:
        raise CatalogueError(
            f"docs/stacks/<slug>.md has no frontmatter title for: {sorted(missing_title)}. "
            f"The catalogue takes each stack's display name from there."
        )
    return stacks


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_catalogue(stacks: list[Stack], categories: list[tuple[str, str]]) -> str:
    """Render the generated block, markers included."""
    known = {key for key, _ in categories}
    unknown = sorted({s.category for s in stacks} - known)
    if unknown:
        raise CatalogueError(
            f"services.yaml uses categories that categories.ts does not define: {unknown}"
        )
    used = [(key, name) for key, name in categories if any(s.category == key for s in stacks)]
    lines = [
        BEGIN_MARKER,
        "",
        f"**{len(stacks)} stacks in {len(used)} categories.** "
        "Each name links to the stack's own page.",
        "",
    ]
    for key, name in used:
        rows = sorted((s for s in stacks if s.category == key), key=lambda s: s.name.casefold())
        lines += [
            f"## {name}",
            "",
            "| Stack | What it is | Tier | Image |",
            "|-------|------------|------|-------|",
        ]
        lines += [
            f"| [{_cell(s.name)}](./{page_slug(s.slug)}.md) | {_cell(s.description)} | {s.tier} | `{s.image}` |"
            for s in rows
        ]
        lines.append("")
    lines.append(END_MARKER)
    return "\n".join(lines)


def replace_block(page: str, block: str) -> str:
    """Swap the text between the markers for ``block``."""
    start = page.find(BEGIN_MARKER)
    end = page.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise CatalogueError("overview.md: the stack-catalogue markers are missing or out of order")
    return page[:start] + block + page[end + len(END_MARKER) :]


def build(repo: Path) -> str:
    """Render the catalogue block from the files in ``repo``."""
    data = yaml.safe_load((repo / "services.yaml").read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not isinstance(data.get("services"), dict):
        raise CatalogueError("services.yaml: no top-level 'services' mapping")
    services = data["services"]
    pages = repo / "docs" / "stacks"
    titles = {
        slug: read_title(page.read_text(encoding="utf-8"))
        if (page := pages / f"{page_slug(slug)}.md").exists()
        else None
        for slug in services
    }
    categories = read_categories(
        (repo / "control-plane" / "src" / "lib" / "categories.ts").read_text(encoding="utf-8")
    )
    return render_catalogue(collect_stacks(services, titles), categories)


def write(repo: Path) -> Path:
    """Regenerate the block in ``docs/stacks/overview.md`` and return the path."""
    target = repo / "docs" / "stacks" / "overview.md"
    target.write_text(
        replace_block(target.read_text(encoding="utf-8"), build(repo)), encoding="utf-8"
    )
    return target


if __name__ == "__main__":  # pragma: no cover — maintenance entry point
    # uv run python -m nexus_deploy.stack_catalogue
    print(write(Path(__file__).resolve().parents[2]))
