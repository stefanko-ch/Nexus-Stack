"""The Kestra admin password survives a rebuild teardown (#942).

A browser remembers the Kestra login, so a password regenerated by every
rebuild teardown locked every user out each morning until they cleared their
site data. teardown.yml therefore excludes the resource from its destroy.

Nothing at runtime would notice if that exclusion stopped matching: a renamed
resource makes `-exclude` a no-op, and the only symptom is the 401 this fixes.
These tests pin the two names to each other.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
WORKFLOWS = REPO_ROOT / ".github" / "workflows"
RESOURCE = "random_password.kestra_admin"


def _destroy_commands(workflow: str) -> list[str]:
    """Every `tofu destroy` command in a workflow, continuation lines joined."""
    text = (WORKFLOWS / workflow).read_text().replace("\\\n", " ")
    return re.findall(r"^\s*(?:if ! )?tofu destroy[^\n]*", text, re.M)


def test_the_resource_exists_under_the_excluded_name() -> None:
    kind, name = RESOURCE.split(".")
    main_tf = (REPO_ROOT / "tofu" / "stack" / "main.tf").read_text()
    assert f'resource "{kind}" "{name}"' in main_tf


def test_the_rebuild_teardown_keeps_the_kestra_password() -> None:
    commands = _destroy_commands("teardown.yml")
    assert len(commands) == 1, commands
    assert f"-exclude={RESOURCE}" in commands[0]


def test_destroy_all_still_removes_it() -> None:
    """Destroy All is the end of the stack; nothing may outlive it."""
    commands = _destroy_commands("destroy-all.yml")
    assert commands, "destroy-all.yml no longer destroys anything"
    for command in commands:
        assert "-exclude" not in command, command
