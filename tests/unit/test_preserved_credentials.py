"""Credentials that a rebuild teardown keeps, because the restored data
already holds them.

Langflow, Label Studio and Memgraph create their login only on the first
start with an empty data directory, and the R2 restore brings that
directory back. A password regenerated by the teardown's destroy would
reach Infisical but never the account. teardown.yml therefore excludes
these resources from its destroy; a renamed resource would make the
exclusion a silent no-op, so the names are pinned here.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
WORKFLOWS = REPO_ROOT / ".github" / "workflows"
PRESERVED = (
    "random_password.langflow_superuser",
    "random_password.langflow_secret_key",
    "random_password.label_studio_admin",
    "random_password.label_studio_user_token",
    "random_password.memgraph",
    "random_password.open_webui_admin",
    "random_password.open_webui_secret_key",
)


def _destroy_commands(workflow: str) -> list[str]:
    text = (WORKFLOWS / workflow).read_text().replace("\\\n", " ")
    return re.findall(r"^\s*(?:if ! )?tofu destroy[^\n]*", text, re.M)


@pytest.mark.parametrize("resource", PRESERVED)
def test_the_resource_exists_under_the_excluded_name(resource: str) -> None:
    kind, name = resource.split(".")
    main_tf = (REPO_ROOT / "tofu" / "stack" / "main.tf").read_text()
    assert f'resource "{kind}" "{name}"' in main_tf


@pytest.mark.parametrize("resource", PRESERVED)
def test_the_rebuild_teardown_keeps_it(resource: str) -> None:
    commands = _destroy_commands("teardown.yml")
    assert len(commands) == 1, commands
    assert f"-exclude={resource}" in commands[0].split()


def test_destroy_all_still_removes_everything() -> None:
    commands = _destroy_commands("destroy-all.yml")
    assert commands, "destroy-all.yml no longer destroys anything"
    for command in commands:
        assert "-exclude" not in command, command
